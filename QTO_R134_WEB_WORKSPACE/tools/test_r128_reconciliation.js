'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync(__dirname+'/../compiled_app.js','utf8');
const start=src.indexOf('function canonicalKey(');
const end=src.indexOf('function saveProject(',start);
assert(start>0&&end>start);
const context={Number,Set,Map,JSON,String,finite:Number.isFinite,MAX_ROWS:20000};
vm.createContext(context);
vm.runInContext(src.slice(start,end),context);
const {canonicalKey,validateBaseline,comparisonRows,reconcileSources}=context;
const a={id:'1',source:'PDF',sourceFile:'p.pdf',page:1,canonicalId:'W1-001',classification:'WALL',kind:'area',quantity:80,unit:'m²',status:'da_xac_nhan'};
const b={id:'2',source:'IFC',sourceFile:'a.ifc',canonicalId:'W1-001',classification:'WALL',kind:'volume',quantity:10,unit:'m³',status:'da_xac_nhan'};
assert.equal(reconcileSources([a,b]).length,1);
assert.equal(reconcileSources([a,{...b,status:'chua_kiem_tra'}]).length,0);
assert.equal(reconcileSources([a,{...b,canonicalId:'W1-002'}]).length,0);
const baseline=validateBaseline([a,b]);
assert.equal(comparisonRows([a,b],baseline).length,0);
let changes=comparisonRows([{...a,quantity:83},{...b,unit:'m²'}],baseline);
assert.equal(JSON.stringify(changes.map(c=>c.change)),JSON.stringify(['CHANGED','UNIT_OR_TYPE_CHANGED']));
assert.equal(changes[0].delta,3);
assert.equal(changes[1].delta,null);
changes=comparisonRows([a,{...b,id:'NEW'}],baseline);
assert.equal(JSON.stringify(changes.map(c=>c.change)),JSON.stringify(['ADDED','REMOVED']));
assert.throws(()=>validateBaseline([{id:'a',quantity:-10,unit:'m'}]));
assert.equal(canonicalKey({canonicalId:'bad|code'}),'');
console.log('R128 reconciliation: 9 assertions groups PASS');
